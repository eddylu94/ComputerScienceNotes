<h1>Project Euler Problem 32</h1>

We shall say that an n-digit number is pandigital if it makes use of all the digits 1 to n exactly once; for example, the 5-digit number, 15234, is 1 through 5 pandigital.
<br>
<br>The product 7254 is unusual, as the identity, 39 × 186 = 7254, containing multiplicand, multiplier, and product is 1 through 9 pandigital.
<br>
<br>Find the sum of all products whose multiplicand/multiplier/product identity can be written as a 1 through 9 pandigital.
<br>
<br>HINT: Some products can be obtained in more than one way so be sure to only include it once in your sum.

