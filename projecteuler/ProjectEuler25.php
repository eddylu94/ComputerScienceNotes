<h1>Project Euler Problem 25</h1>

The Fibonacci sequence is defined by the recurrence relation:
<br>
<br>Fn = F_n−1 + F_n−2, where F_1 = 1 and F_2 = 1.
<br>Hence the first 12 terms will be:
<br>
<br>F_1 = 1
<br>F_2 = 1
<br>F_3 = 2
<br>F_4 = 3
<br>F_5 = 5
<br>F_6 = 8
<br>F_7 = 13
<br>F_8 = 21
<br>F_9 = 34
<br>F_10 = 55
<br>F_11 = 89
<br>F_12 = 144
<br>The 12th term, F12, is the first term to contain three digits.
<br>
<br>What is the index of the first term in the Fibonacci sequence to contain 1000 digits?

