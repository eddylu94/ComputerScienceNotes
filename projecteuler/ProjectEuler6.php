<h1>Project Euler Problem 6</h1>

The sum of the squares of the first ten natural numbers is,
<br>
<br>1^2 + 2^2 + ... + 10^2 = 385
<br>The square of the sum of the first ten natural numbers is,
<br>
<br>(1 + 2 + ... + 10)^2 = 55^2 = 3025
<br>Hence the difference between the sum of the squares of the first ten natural numbers and the square of the sum is 3025 − 385 = 2640.
<br>
<br>Find the difference between the sum of the squares of the first one hundred natural numbers and the square of the sum.

